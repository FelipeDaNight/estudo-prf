const fs=require("fs"),assert=require("assert");
const d=JSON.parse(fs.readFileSync(__dirname+"/../bancos/ctb-prf.json","utf8"));
const A={};let n=0,lac=0;
d.blocos.forEach(b=>{assert.ok(b.id&&b.dia&&b.rotulo&&b.lei==="CTB");b.artigos.forEach(a=>{n++;A[a.art]=a;
  const txt=a.itens.map(i=>i.t).join(" ");
  assert.ok(!/Redação dada|Incluíd[oa] pela|\(Vigência\)|planalto|Produção de efeitos/.test(txt),"anotação sobrando em "+a.art);
  assert.ok(txt.length>10,"vazio "+a.art);
  a.lacunas.forEach(l=>{lac++;assert.strictEqual((l.c.match(/____/g)||[]).length,1,"1 lacuna em "+a.art+": "+l.c.slice(0,60));assert.ok(l.r&&l.r.length<260,"resposta "+a.art);});
  if(a.resumo!==undefined) assert.ok(a.resumo.length>15,"resumo curto "+a.art);
});});
assert.ok(n>=480,"artigos "+n);
assert.ok(A["Art. 267"].itens[0].t.includes("Deverá ser imposta"));
assert.ok(!JSON.stringify(d).includes("Poderá ser imposta a penalidade de advertência"));
assert.strictEqual(A["Art. 165"].ficha.natureza,"gravíssima");assert.strictEqual(A["Art. 165"].ficha.pontos,7);
assert.ok(A["Art. 165-B"]&&A["Art. 165-C"],"14.599/2023 presente");
assert.ok(A["Art. 61"].itens.some(i=>/110 km\/h/.test(i.t)));
assert.ok(A["Art. 218"].pontos.join(" ").includes("20%"));
assert.ok(A["Art. 20"].itens[0].t.includes("Polícia Rodoviária Federal"));
assert.ok(A["Acostamento"]&&A["Acostamento"].lacunas[0].r==="ACOSTAMENTO");
console.log("CTB (dados): ok,",d.blocos.length,"dias,",n,"itens,",lac,"lacunas");
